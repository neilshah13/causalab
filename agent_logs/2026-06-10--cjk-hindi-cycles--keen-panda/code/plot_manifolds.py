# Figure 5 — Pullback: optimized vs linear r² (EN and FR)
# ══════════════════════════════════════════════════════════════════════════════
def fig5_pullback_comparison():
    langs = ["en", "fr"]
    x = np.arange(len(langs))
    w = 0.32

    fig, ax = plt.subplots(figsize=(6, 5))

    opt_vals = [PULLBACK[l][0] for l in langs]
    lin_vals = [PULLBACK[l][1] for l in langs]

    bars_opt = ax.bar(x - w/2, opt_vals, w, color=[LANG_COLORS[l] for l in langs],
                      alpha=0.9, label="Geodesic (optimized)", edgecolor="white")
    bars_lin = ax.bar(x + w/2, lin_vals, w, color=[LANG_COLORS[l] for l in langs],
                      alpha=0.45, label="Linear", edgecolor="white", hatch="///")

    for bar, val in zip(bars_opt, opt_vals):
        ax.text(bar.get_x() + bar.get_width()/2, val + 0.01, f"{val:.3f}",
                ha="center", va="bottom", fontsize=9, fontweight="bold")
    for bar, val in zip(bars_lin, lin_vals):
        ax.text(bar.get_x() + bar.get_width()/2, val + 0.01, f"{val:.3f}",
                ha="center", va="bottom", fontsize=9)

    # Annotation arrows showing which is better
    for i, lang in enumerate(langs):
        opt, lin = PULLBACK[lang]
        better = "geo" if opt > lin else "lin"
        color = LANG_COLORS[lang]
        sign = "+" if opt > lin else "−"
        delta = abs(opt - lin)
        ax.annotate(
            f"{sign}{delta:.2f}",
            xy=(i + w/2 if better == "lin" else i - w/2,
                max(opt, lin) + 0.03),
            ha="center", fontsize=9, color=color, fontstyle="italic"
        )

    ax.set_xticks(x)
    ax.set_xticklabels([LANG_LABELS[l] for l in langs], fontsize=11)
    ax.set_ylabel("Path recapitulation r² (k=32 neighbours)", fontsize=10)
    ax.set_ylim(0, 0.85)
    ax.set_title(
        "Pullback Quality: Geodesic vs Linear Paths\n"
        "(EN ring: geodesic > linear  |  FR no-ring: linear > geodesic)",
        fontsize=11
    )
    ax.legend(fontsize=9)
    ax.axhline(0.5, color="gray", lw=0.8, ls=":", alpha=0.5)

    fig.tight_layout()
    path = os.path.join(FIGURES_DIR, "fig5_pullback_comparison.pdf")
    fig.savefig(path, bbox_inches="tight")
    fig.savefig(path.replace(".pdf", ".png"), bbox_inches="tight", dpi=150)
    print(f"Saved {path}")
    plt.close(fig)


