# Figure 4 — Subspace overlap heatmap (all 6 pairs)
# ══════════════════════════════════════════════════════════════════════════════
def fig4_overlap_heatmap():
    langs_ord = ["en", "fr", "zh", "ja"]
    n = len(langs_ord)
    matrix = np.full((n, n), np.nan)
    np.fill_diagonal(matrix, 1.0)

    for key, vals in DATA["pairwise_alignment"].items():
        la, lb = key.split("_vs_")
        if la in langs_ord and lb in langs_ord:
            i, j = langs_ord.index(la), langs_ord.index(lb)
            matrix[i, j] = vals["overlap"]
            matrix[j, i] = vals["overlap"]

    fig, ax = plt.subplots(figsize=(6, 5))
    im = ax.imshow(matrix, cmap="YlOrRd_r", vmin=0, vmax=1, aspect="auto")

    labels = [LANG_LABELS[l] for l in langs_ord]
    ax.set_xticks(range(n)); ax.set_xticklabels(labels, fontsize=10)
    ax.set_yticks(range(n)); ax.set_yticklabels(labels, fontsize=10)
    ax.set_title("Weekday Ring Subspace Overlap\ncos(θ₁)·cos(θ₂)  —  0=orthogonal, 1=identical",
                 fontsize=11)

    for i in range(n):
        for j in range(n):
            val = matrix[i, j]
            if not np.isnan(val):
                text_color = "white" if val < 0.3 else "black"
                ax.text(j, i, f"{val:.3f}", ha="center", va="center",
                        fontsize=10, color=text_color, fontweight="bold")

    plt.colorbar(im, ax=ax, label="Overlap score")
    fig.tight_layout()
    path = os.path.join(FIGURES_DIR, "fig4_overlap_heatmap.pdf")
    fig.savefig(path, bbox_inches="tight")
    fig.savefig(path.replace(".pdf", ".png"), bbox_inches="tight", dpi=150)
    print(f"Saved {path}")
    plt.close(fig)


