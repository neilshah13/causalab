def smooth_curve(pts_2d: np.ndarray, closed: bool, n_pts: int = 300) -> np.ndarray:
    """Fit and sample a smooth spline through 2D points."""
    if closed:
        p = np.vstack([pts_2d, pts_2d[0]])
        tck, _ = splprep([p[:, 0], p[:, 1]], s=0, per=True)
    else:
        k = min(3, len(pts_2d) - 1)
        tck, _ = splprep([pts_2d[:, 0], pts_2d[:, 1]], s=0, per=False, k=k)
    u = np.linspace(0, 1, n_pts)
    x, y = splev(u, tck)
    return np.column_stack([x, y])


def angle_order(pts: np.ndarray, center: np.ndarray | None = None) -> np.ndarray:
    """Return indices that sort pts by angle around center."""
    c = center if center is not None else pts.mean(axis=0)
    angles = np.arctan2(pts[:, 1] - c[1], pts[:, 0] - c[0])
    return np.argsort(angles)


