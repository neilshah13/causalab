# Figure 3 — Cross-lingual subspace alignment: pairwise joint projections
# ══════════════════════════════════════════════════════════════════════════════
def fig3_subspace_alignment():
    main_pairs = [("en", "zh"), ("en", "fr"), ("zh", "ja")]
    pair_titles = {
        "en_vs_zh": "English ↔ Chinese",
        "en_vs_fr": "English ↔ French",
        "zh_vs_ja": "Chinese ↔ Japanese",
    }

    fig, axes = plt.subplots(1, 3, figsize=(15, 5))
    fig.suptitle(
        "Cross-lingual Subspace Alignment: Pairwise Joint 2-D Projections\n"
        "(Both languages' centroids projected into their shared PCA plane)",
        fontsize=12
    )

    for ax, (la, lb) in zip(axes, main_pairs):
        key = f"{la}_vs_{lb}"
        pair_data = DATA["pairwise_joint_embedding"][key]
        align = DATA["pairwise_alignment"][key]

        for lang in [la, lb]:
            proj = pair_data["projections"][lang]
            pts = np.array(proj["coords"])
            r = proj["radius"]
            entity_names = DATA["entity_names"][lang]
            color = LANG_COLORS[lang]
            is_ring = LANG_RING[lang]
            center = pts.mean(axis=0)

            if is_ring:
                order = angle_order(pts, center)
            else:
                order = np.arange(7)
            ordered_pts = pts[order]
            curve = smooth_curve(ordered_pts, closed=is_ring)

            ls = "-" if is_ring else "--"
            ax.plot(curve[:, 0], curve[:, 1], color=color, lw=2.5, ls=ls, alpha=0.7)
            for i, name in enumerate(entity_names):
                ax.scatter(pts[i, 0], pts[i, 1], color=color, s=90,
                           edgecolors="white", linewidths=0.7, zorder=3)
            # Language label
            ax.text(center[0], center[1], LANG_LABELS[lang],
                    color=color, fontsize=8, ha="center", va="center",
                    fontweight="bold",
                    bbox=dict(boxstyle="round,pad=0.2", fc="white", alpha=0.7, ec="none"))

        theta1 = align["theta1"]
        theta2 = align["theta2"]
        overlap = align["overlap"]
        r_a = pair_data["projections"][la]["radius"]
        r_b = pair_data["projections"][lb]["radius"]
        ratio = max(r_a, r_b) / (min(r_a, r_b) + 1e-10)

        ax.set_title(
            f"{pair_titles[key]}\n"
            f"θ₁={theta1:.1f}°, θ₂={theta2:.1f}°  |  Overlap={overlap:.3f}  |  Radius ratio={ratio:.1f}×",
            fontsize=9
        )
        ax.set_aspect("equal")
        ax.set_xlabel("Pair PC 1", fontsize=8)
        ax.set_ylabel("Pair PC 2", fontsize=8)
        ax.tick_params(labelsize=7)

    fig.tight_layout(rect=[0, 0, 1, 0.92])
    path = os.path.join(FIGURES_DIR, "fig3_subspace_alignment.pdf")
    fig.savefig(path, bbox_inches="tight")
    fig.savefig(path.replace(".pdf", ".png"), bbox_inches="tight", dpi=150)
    print(f"Saved {path}")
    plt.close(fig)


