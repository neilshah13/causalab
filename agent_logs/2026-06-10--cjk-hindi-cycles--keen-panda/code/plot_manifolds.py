# Figure 1 — Per-language manifold panels (paper-style)
# ══════════════════════════════════════════════════════════════════════════════
def fig1_language_manifolds():
    fig, axes = plt.subplots(2, 2, figsize=(10, 10))
    fig.suptitle(
        "Weekday Cyclic Arithmetic Manifolds — Llama 3.1 8B, Layer 28\n"
        "(centroid positions in each language's best-fit 2-D subspace of pca_k64)",
        fontsize=12, y=0.98
    )

    for ax, lang in zip(axes.flat, LANGS):
        lang_data = DATA["per_language"][lang]
        entity_names = DATA["entity_names"][lang]
        is_ring = LANG_RING[lang]

        pts = np.array(lang_data["centroids_2d"])  # (7, 2)
        center = np.array(lang_data["circle_center"])
        radius = lang_data["circle_radius"]
        color = LANG_COLORS[lang]

        # Order for smooth curve
        if is_ring:
            order = angle_order(pts, center)
        else:
            order = np.arange(7)  # natural weekday order Mon→Sun
        ordered_pts = pts[order]

        # Smooth curve
        curve = smooth_curve(ordered_pts, closed=is_ring)

        # Draw curve
        ls = "-" if is_ring else "--"
        ax.plot(curve[:, 0], curve[:, 1], color=color, lw=2, ls=ls, alpha=0.6,
                zorder=1, label="Fitted ring" if is_ring else "Fitted spline")

        if is_ring:
            # Draw best-fit circle for reference
            theta = np.linspace(0, 2 * np.pi, 300)
            cx, cy = center
            ax.plot(cx + radius * np.cos(theta), cy + radius * np.sin(theta),
                    color=color, lw=0.8, ls=":", alpha=0.3, zorder=0)

        # Scatter centroids colored by weekday
        for i, name in enumerate(entity_names):
            dc = DAY_COLORS[i]
            ax.scatter(pts[i, 0], pts[i, 1], color=dc, s=120, zorder=3,
                       edgecolors="white", linewidths=0.8)
            # Label offset to avoid overlap
            dx, dy = pts[i, 0] - pts.mean(0)[0], pts[i, 1] - pts.mean(0)[1]
            norm = np.sqrt(dx**2 + dy**2) + 1e-8
            ax.annotate(name, (pts[i, 0], pts[i, 1]),
                        xytext=(pts[i, 0] + 0.25 * dx / norm * radius,
                                pts[i, 1] + 0.25 * dy / norm * radius),
                        fontsize=7.5, ha="center", va="center",
                        bbox=dict(boxstyle="round,pad=0.1", fc="white", alpha=0.6, ec="none"))

        ring_str = "Closed ring ✓" if is_ring else "Open spline"
        ax.set_title(
            f"{LANG_LABELS[lang]}  ({lang.upper()})  |  Gate {GATE_ACC[lang]:.0f}%\n"
            f"{ring_str}  |  Isometry r = {ISOMETRY_R[lang]:+.3f}  |  Coherence = {COHERENCE[lang]:.3f}",
            fontsize=9.5, color=color
        )
        ax.set_xlabel("PC 1 (language subspace)", fontsize=8)
        ax.set_ylabel("PC 2 (language subspace)", fontsize=8)
        ax.set_aspect("equal")
        ax.tick_params(labelsize=7)

    fig.tight_layout(rect=[0, 0, 1, 0.97])
    path = os.path.join(FIGURES_DIR, "fig1_language_manifolds.pdf")
    fig.savefig(path, bbox_inches="tight")
    fig.savefig(path.replace(".pdf", ".png"), bbox_inches="tight", dpi=150)
